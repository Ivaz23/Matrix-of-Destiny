export const getArcanaProfile = (arcanaNumber: number): ArcanaPsychologyProfile => {
  const norm = arcanaNumber > 22 ? ((arcanaNumber - 1) % 22) + 1 : (arcanaNumber <= 0 ? 22 : arcanaNumber);
  return ARCANA_PSYCHOLOGY_DATA[norm] || ARCANA_PSYCHOLOGY_DATA[1];
};

export interface MatrixPsychologicalMap {
  dayProfile: ArcanaPsychologyProfile;     // Личность & Визитка (A)
  monthProfile: ArcanaPsychologyProfile;   // Таланты & Связь с Духом (B)
  yearProfile: ArcanaPsychologyProfile;    // Деньги & Материализация (C)
  karmicProfile: ArcanaPsychologyProfile;  // Кармический Хвост & Главный Минус (D)
  comfortProfile: ArcanaPsychologyProfile; // Центр Души & Комфорт (E)
  destinyProfile: ArcanaPsychologyProfile; // Высшее Предназначение (Destiny)
  
  coreConflictAnalysis: {
    title: string;
    description: string;
    resolutionKey: string;
  };
  
  overallResourceRecommendation: string;
}

export const buildMatrixPsychologicalMap = (matrix: {
  day: number;
  month: number;
  year: number;
  bottom: number;
  center: number;
  destiny: number;
}): MatrixPsychologicalMap => {
  const dayP = getArcanaProfile(matrix.day);
  const monthP = getArcanaProfile(matrix.month);
  const yearP = getArcanaProfile(matrix.year);
  const karmicP = getArcanaProfile(matrix.bottom);
  const comfortP = getArcanaProfile(matrix.center);
  const destinyP = getArcanaProfile(matrix.destiny);

  // Analyze fundamental psychological tension (e.g., Day vs Karmic Tail)
  let conflictTitle = `Синтез Энергии Проявления (${matrix.day} Аркан) и Кармического Урока (${matrix.bottom} Аркан)`;
  let conflictDesc = `Ваша социальная визитка стремится проявляться через качества «${dayP.name}» (${dayP.archetype}), однако базовый кармический триггер укоренен в тени «${karmicP.name}» (${karmicP.minusTraits.egoTraps}).`;
  let resolutionKey = `Чтобы энергия личности (${matrix.day}) раскрылась на 100% в плюс, необходимо в первую очередь осознать ловушку ${matrix.bottom}-го аркана: ${karmicP.transformationKeys[0] || 'отпустить страх и контроль'}.`;

  const overallRec = `Ваша ключевая точка баланса — ${comfortP.name} (Центр матрицы ${matrix.center}). Когда вы возвращаетесь в состояние ${comfortP.archetype}, все остальные каналы (включая финансы ${matrix.year} аркана и таланты ${matrix.month} аркана) автоматически переходят на высокие вибрации.`;

  return {
    dayProfile: dayP,
    monthProfile: monthP,
    yearProfile: yearP,
    karmicProfile: karmicP,
    comfortProfile: comfortP,
    destinyProfile: destinyP,
    coreConflictAnalysis: {
      title: conflictTitle,
      description: conflictDesc,
      resolutionKey
    },
    overallResourceRecommendation: overallRec
  };
};

