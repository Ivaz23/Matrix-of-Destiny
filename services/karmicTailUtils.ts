/**
 * Computes the 3 arcana forming the Karmic Tail (D, D1, D2)
 */
export function calculateKarmicTailTriad(matrix: MatrixNumbers): [number, number, number] {
  const d = matrix.bottom;
  const d1 = reduceArcana(matrix.bottom + matrix.center);
  const d2 = reduceArcana(matrix.bottom + d1);
  return [d, d1, d2];
}

/**
 * Returns full karmic tail details (either from curated database or dynamically synthesized)
 */
