export function getConsciousnessNumber(day: number): number {
  if (day <= 0 || day > 31) return 1;
  const digits = String(day).split('').map(Number);
  let sum = digits.reduce((a, b) => a + b, 0);
  while (sum > 9) {
    sum = String(sum).split('').map(Number).reduce((a, b) => a + b, 0);
  }
  return sum;
}

